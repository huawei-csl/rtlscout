// Golden-referenced directed testbench: compares the DUT against the embedded
// golden reference (fp_add_e8f23_ref, the benchmark's reference Verilog) over
// ~16.8M enumerated vectors -- no stimuli file. Mirrors the fpadd_f16 tb, but
// the coverage claim is WEAKER and deliberately so: at f32 the subnormal space
// is 2^24 per operand, so f16's exhaustive subnormal enumeration (2^11) is not
// reachable. Subnormals are SAMPLED here (corners + LFSR), not enumerated.
//   1. addition-specific boundary pairs (carry-out of subnormal, exact
//      cancellation, Inf/NaN propagation, round-to-even ties, max-normal overflow)
//   2. sampled subnormal/zero a (2048) x structured b (2048)
//   3. structured a (2048) x sampled subnormal/zero b (2048)
//   4. structured a (2048) x structured b (2048) -- covers ALL 256x256 exponent
//      pairs, i.e. every alignment-shift distance the adder can see
//   5. 2^22 LFSR-driven broad pairs
// Structured operands: both signs x all 256 exponents (incl. 0 subnormal and
// 255 Inf/NaN) x 4 mantissas (0, LSB, max, LFSR).
module tb;
  logic [31:0] a, b, y, y_ref;
  int errors;
  longint total;

  fp_add_e8f23 dut (.a(a), .b(b), .y(y));
  fp_add_e8f23_ref refm (.a(a), .b(b), .y(y_ref));

  // maximal-length 32-bit Galois LFSR (taps 32,31,29,1)
  function automatic [31:0] lfsr_next(input [31:0] s);
    lfsr_next = (s >> 1) ^ (s[0] ? 32'hD0000001 : 32'h00000000);
  endfunction

  logic [31:0] structured [0:2047];
  logic [31:0] subnorm    [0:2047];
  localparam logic [22:0] MANT_CORNERS [0:7] =
      '{23'h000000, 23'h000001, 23'h000002, 23'h7FFFFF,
        23'h7FFFFE, 23'h555555, 23'h2AAAAA, 23'h400000};

  task automatic check();
    #1;
    total = total + 1;
    if (y !== y_ref) begin
      if (errors < 10)
        $display("TB_ERROR a=%0h b=%0h expected_y=%0h actual_y=%0h", a, b, y_ref, y);
      errors = errors + 1;
    end
  endtask

  logic [31:0] lfsr, ra, rb;
  logic [22:0] mant;
  int idx;

  initial begin
    errors = 0; total = 0;

    // structured: 2 signs x 256 exponents x 4 mantissas = 2048
    lfsr = 32'hACE12345;
    idx = 0;
    for (int s = 0; s < 2; s++)
      for (int e = 0; e < 256; e++)
        for (int m = 0; m < 4; m++) begin
          case (m)
            0: mant = 23'h000000;   // exact power of two / Inf when e=255
            1: mant = 23'h000001;   // LSB set / quiet-NaN pattern when e=255
            2: mant = 23'h7FFFFF;   // all ones
            default: begin lfsr = lfsr_next(lfsr); mant = lfsr[22:0]; end
          endcase
          structured[idx] = {s[0], e[7:0], mant};
          idx = idx + 1;
        end

    // sampled subnormals/zero: 2 signs x 1024 mantissa patterns (exponent 0)
    idx = 0;
    for (int s = 0; s < 2; s++)
      for (int k = 0; k < 1024; k++) begin
        if (k < 8) mant = MANT_CORNERS[k];
        else begin lfsr = lfsr_next(lfsr); mant = lfsr[22:0]; end
        subnorm[idx] = {s[0], 8'h00, mant};
        idx = idx + 1;
      end

    // 1. addition-specific boundary pairs
    a = 32'h007FFFFF; b = 32'h00000001; check();  // subnormal carry into normal
    a = 32'h3F800000; b = 32'hBF800000; check();  // exact cancellation -> +0
    a = 32'h00000001; b = 32'h7F7FFFFF; check();  // min subnormal + max normal
    a = 32'h7F800000; b = 32'hFF800000; check();  // +Inf + -Inf -> NaN
    a = 32'h7F800000; b = 32'h3F800000; check();  // Inf + finite
    a = 32'h7FC00000; b = 32'h3F800000; check();  // NaN propagation
    a = 32'h7F7FFFFF; b = 32'h7F7FFFFF; check();  // overflow to Inf
    a = 32'h3F800000; b = 32'h33800000; check();  // round-to-even tie
    a = 32'h3F800001; b = 32'h33800000; check();  // tie, odd LSB
    a = 32'h00000000; b = 32'h80000000; check();  // +0 + -0
    a = 32'h80000000; b = 32'h80000000; check();  // -0 + -0 -> -0
    a = 32'h00800000; b = 32'h807FFFFF; check();  // min normal - max subnormal

    // 2. sampled subnormal a x structured b
    for (int i = 0; i < 2048; i++) begin
      a = subnorm[i];
      for (int j = 0; j < 2048; j++) begin b = structured[j]; check(); end
    end
    // 3. structured a x sampled subnormal b
    for (int i = 0; i < 2048; i++) begin
      a = structured[i];
      for (int j = 0; j < 2048; j++) begin b = subnorm[j]; check(); end
    end
    // 4. structured x structured -- every exponent pair
    for (int i = 0; i < 2048; i++) begin
      a = structured[i];
      for (int j = 0; j < 2048; j++) begin b = structured[j]; check(); end
    end
    // 5. broad LFSR pairs
    ra = 32'h00000001; rb = 32'hDEADBEEF;
    for (int k = 0; k < (1 << 22); k++) begin
      ra = lfsr_next(ra); rb = lfsr_next(lfsr_next(rb));
      a = ra; b = rb; check();
    end

    $display("TB_SUMMARY total=%0d errors=%0d", total, errors);
    if (errors != 0) $fatal(1, "FAIL");
    $display("PASS");
    $finish;
  end
endmodule

